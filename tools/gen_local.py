"""Single-machine mode: generate compose/local.compose.yml and out-local/config/testbed.yaml.

All emulated hosts (2 cloud, 2 fog, 4 edge by default) run on one Docker Desktop. Each host is a
network container (its own namespace and IP on the bridge network) plus its control agent and six
data-store containers that share that namespace. Table 7 link profiles and partitions act on eth0.

    docker run --rm -v <deploy-dir>:/work -w /work odb-net:latest python3 tools/gen_local.py [options]

Options (CPU/memory limits are per data-store container, i.e. per emulated host, because only the
system under test runs):
  --cloud N --fog N --edge N          number of emulated hosts per tier (default 2 2 4)
  --cpus-cloud C --mem-cloud M        default 2 / 3g
  --cpus-fog C   --mem-fog M          default 2 / 3g
  --cpus-edge C  --mem-edge M         default 1 / 2g
  --subnet 10.88.0                    first three octets of the /24 bridge network
"""
import argparse, json, os, secrets

ap = argparse.ArgumentParser()
for t, n, c, m in (("cloud", 2, "2", "3g"), ("fog", 2, "2", "3g"), ("edge", 4, "1", "2g")):
    ap.add_argument(f"--{t}", type=int, default=n)
    ap.add_argument(f"--cpus-{t}", default=c)
    ap.add_argument(f"--mem-{t}", default=m)
ap.add_argument("--subnet", default="10.88.0")
a = ap.parse_args()

SYS = ["optimusdb", "corrosion", "gun", "autobase", "iroh", "opendht"]
P = {"optimusdb": 8089, "corrosion": 8080, "gun": 7004, "autobase": 7005, "iroh": 7006, "opendht": 8000}
VOLS = {"optimusdb": [("optimusdb-root", "/root"), ("optimusdb-data", "/data")], "corrosion": [("corrosion-data", "/data")],
        "gun": [("gun-data", "/data")], "autobase": [("autobase-data", "/data")], "iroh": [("iroh-data", "/data")], "opendht": []}
AGENT_MOUNT = {"optimusdb-root": "/volumes/optimusdb-root", "optimusdb-data": "/volumes/optimusdb-data",
               "corrosion-data": "/volumes/corrosion", "gun-data": "/volumes/gun", "autobase-data": "/volumes/autobase", "iroh-data": "/volumes/iroh"}

os.makedirs("out-local/config", exist_ok=True)
tokf = "out-local/.agent_token"
token = open(tokf).read().strip() if os.path.exists(tokf) else secrets.token_hex(24)
open(tokf, "w").write(token)

hosts, k = [], 0
for tier in ("cloud", "fog", "edge"):
    for j in range(getattr(a, tier)):
        hosts.append(dict(name=f"{tier}-{chr(ord('a') + j)}", role=tier, ip=f"{a.subnet}.{11 + k}",
                          cpus=getattr(a, f"cpus_{tier}"), mem=getattr(a, f"mem_{tier}")))
        k += 1

services, volumes = {}, {}
services["bench"] = {
    "image": "odb-bench:latest", "container_name": "odb-bench", "hostname": "bench", "init": True,
    "networks": {"odbnet": {"ipv4_address": f"{a.subnet}.2"}},
    "volumes": ["../out-local/config:/config:ro", "../results:/results", "../trace:/trace:ro"],
    "restart": "unless-stopped"}
for h in hosts:
    n = h["name"]; pre = f"odb-{n}-"
    services[f"net-{n}"] = {
        "image": "odb-net:latest", "container_name": f"{pre}net", "hostname": n, "init": True,
        "cap_add": ["NET_ADMIN"], "networks": {"odbnet": {"ipv4_address": h["ip"]}}, "restart": "unless-stopped"}
    volumes[f"{n}-runtime"] = {}
    agent_vols = ["/var/run/docker.sock:/var/run/docker.sock", f"{n}-runtime:/runtime"]
    for s in SYS:
        for v, _ in VOLS[s]:
            volumes[f"{n}-{v}"] = {}; agent_vols.append(f"{n}-{v}:{AGENT_MOUNT[v]}")
    services[f"agent-{n}"] = {
        "image": "odb-agent:latest", "container_name": f"{pre}agent", "network_mode": f"service:net-{n}",
        "depends_on": [f"net-{n}"], "cap_add": ["NET_ADMIN"], "restart": "unless-stopped",
        "environment": {"AGENT_TOKEN": token, "HOST_NAME": n, "ROLE": h["role"], "OVERLAY_IP": h["ip"],
                        "CONTAINER_PREFIX": pre, "IFACE": "eth0"},
        "volumes": agent_vols}
    for s in SYS:
        env = {"OVERLAY_IP": h["ip"], "HOST_NAME": n}
        if s == "optimusdb": env.update(METADATA_AUTO_ENRICH="false", METADATA_ENRICHMENT_ENABLED="false", AGENT_NAME=n)
        services[f"{s}-{n}"] = {
            "image": f"odb-{s}:latest", "container_name": f"{pre}{s}", "network_mode": f"service:net-{n}",
            "depends_on": [f"net-{n}"], "restart": "no", "cpus": float(h["cpus"]), "mem_limit": h["mem"],
            "environment": env,
            "volumes": [f"{n}-{v}:{mnt}" for v, mnt in VOLS[s]] + [f"{n}-runtime:/runtime:ro"]}

compose = {"name": "odb-local", "services": services, "volumes": volumes,
           "networks": {"odbnet": {"name": "odbnet", "driver": "bridge",
                                   "ipam": {"config": [{"subnet": f"{a.subnet}.0/24", "gateway": f"{a.subnet}.1"}]}}}}
with open("compose/local.compose.yml", "w") as f:
    f.write("# generated by tools/gen_local.py (single-machine mode) - JSON is valid YAML\n")
    json.dump(compose, f, indent=1)

first = lambda role: next(h for h in hosts if h["role"] == role)
TYPE = {"optimusdb": {"type": "optimusdb", "strategy": "LOCAL_THEN_REMOTE_MERGE"}, "corrosion": {"type": "corrosion"},
        "gun": {"type": "http", "name": "gun"}, "autobase": {"type": "http", "name": "autobase"},
        "iroh": {"type": "http", "name": "iroh"}, "opendht": {"type": "opendht"}}
c1, e1 = first("cloud"), first("edge")
cfg = {
    "seed": 20261101, "settle_s": 20, "mode": "single-machine",
    "run": {"rate": 50, "duration_s": 300, "warmup_s": 60, "poisson": True, "client_workers": 4},
    "data": {"records": 100000},
    "cluster": {"token": token, "iface": "eth0",
                "hosts": [{"name": "bench", "role": "bench", "ip": f"{a.subnet}.2"}] +
                         [{"name": h["name"], "role": h["role"], "ip": h["ip"], "cpus": float(h["cpus"]), "mem": h["mem"]}
                          for h in hosts]},
    "agents": [f"http://{h['ip']}:8089" for h in hosts],
    "initiators": {t: f"http://{first(t)['ip']}:8089" for t in ("cloud", "fog", "edge")},
    "links": {   # Table 7 (+ two derived links), applied on eth0 of every emulated host
        "cloud-cloud": {"delay_ms": 5, "jitter_ms": 1, "loss_pct": 0.0, "rate_mbit": 1000},
        "cloud-fog": {"delay_ms": 20, "jitter_ms": 4, "loss_pct": 0.1, "rate_mbit": 100},
        "fog-fog": {"delay_ms": 2, "jitter_ms": 0.5, "loss_pct": 0.0, "rate_mbit": 1000},
        "fog-edge": {"delay_ms": 50, "jitter_ms": 10, "loss_pct": 0.5, "rate_mbit": 10},
        "cloud-edge": {"delay_ms": 70, "jitter_ms": 11, "loss_pct": 0.6, "rate_mbit": 10},
        "edge-edge": {"delay_ms": 2, "jitter_ms": 0.5, "loss_pct": 0.0, "rate_mbit": 100}},
    "systems": {s: dict(TYPE[s], base_url=f"http://{c1['ip']}:{P[s]}") for s in P},
    "replicas": {s: [f"http://{h['ip']}:{P[s]}" for h in hosts] for s in P if s != "optimusdb"},
    "edge_override": {s: {"base_url": f"http://{e1['ip']}:{P[s]}"} for s in P},
    "e3_targets": [{"system": "optimusdb", "path": "crdt"}, {"system": "optimusdb", "path": "sqlite", "override": {"sql_tables": True}},
                   {"system": "corrosion", "path": "sql"}, {"system": "gun", "path": "client_filter"},
                   {"system": "autobase", "path": "range_client_filter"}, {"system": "iroh", "path": "prefix_client_filter"},
                   {"system": "opendht", "path": "key_only"}],
    "edge_systems": list(P),
    "reset": {s: "cluster" for s in P} | {f"{s}_edge": "cluster" for s in P},
}
# Optional overrides kept outside the generated file (it is rewritten on every deploy), e.g.
#   testbed-overrides.json: {"optimusdb_runtime": {"log_level": "INFO", "env": {"SERVICE_CONCURRENCY": 1}}}
if os.path.exists("testbed-overrides.json"):
    with open("testbed-overrides.json") as f:
        ov = json.load(f)
    for k, v in ov.items():
        cfg[k] = dict(cfg[k], **v) if isinstance(v, dict) and isinstance(cfg.get(k), dict) else v
    print("applied testbed-overrides.json:", ", ".join(ov))
with open("out-local/config/testbed.yaml", "w") as f:
    f.write("# generated by tools/gen_local.py (single-machine mode)\n")
    json.dump(cfg, f, indent=2)

tot_c = {t: sum(float(h["cpus"]) for h in hosts if h["role"] == t) for t in ("cloud", "fog", "edge")}
print(f"{'host':9} {'role':6} {'IP':13} limits per data store")
for h in hosts: print(f"{h['name']:9} {h['role']:6} {h['ip']:13} cpus={h['cpus']} mem={h['mem']}")
print(f"CPU needed while one system runs: {sum(tot_c.values()):g} cores (+ ~1-2 for the bench container)")
print("wrote compose/local.compose.yml and out-local/config/testbed.yaml")
